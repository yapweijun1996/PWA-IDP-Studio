import { readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const catalog = new URL('../icons/catalog/', import.meta.url);
const target = new URL('../src/ui/icons.generated.ts', import.meta.url);
const elements = new Set(['svg', 'path', 'circle', 'rect', 'line', 'polyline', 'polygon', 'ellipse']);
const attributes = new Set(['xmlns', 'viewBox', 'fill', 'stroke', 'stroke-width', 'stroke-linecap', 'stroke-linejoin', 'aria-hidden', 'd', 'cx', 'cy', 'r', 'x', 'y', 'x1', 'y1', 'x2', 'y2', 'width', 'height', 'rx', 'ry', 'points', 'fill-rule', 'clip-rule', 'opacity', 'stroke-dasharray', 'stroke-dashoffset']);

export function validateSvg(source) {
  const stack = [];
  let position = 0;
  let innerStart = 0;
  let innerEnd = 0;
  let roots = 0;
  const tags = /<\/?[A-Za-z][^<>]*>/g;
  for (const match of source.matchAll(tags)) {
    if (source.slice(position, match.index).trim()) throw new Error('Unexpected SVG content');
    position = match.index + match[0].length;
    const tag = /^<(\/?)(([A-Za-z][\w-]*))([\s\S]*?)(\/?)>$/.exec(match[0]);
    if (!tag) throw new Error('Malformed SVG tag');
    const [, closing, name, , rest, selfClosing] = tag;
    if (!elements.has(name)) throw new Error(`Forbidden element: ${name}`);
    if (closing) {
      if (rest.trim() || selfClosing || stack.pop() !== name) throw new Error('Unbalanced SVG');
      if (!stack.length) innerEnd = match.index;
      continue;
    }
    const values = new Map();
    let offset = 0;
    const attrs = /\s+([A-Za-z][\w:-]*)\s*=\s*("[^"]*"|'[^']*')/g;
    for (const attr of rest.matchAll(attrs)) {
      if (rest.slice(offset, attr.index).trim()) throw new Error('Malformed attribute');
      offset = attr.index + attr[0].length;
      const key = attr[1];
      const value = attr[2].slice(1, -1);
      if (!attributes.has(key) || /^on/i.test(key) || /href/i.test(key) || values.has(key)) throw new Error(`Forbidden attribute: ${key}`);
      if (/[<>&]/.test(value) || /url\s*\(|javascript:|data:/i.test(value)) throw new Error('Unsafe attribute value');
      if (['fill', 'stroke'].includes(key) && !['none', 'currentColor'].includes(value)) throw new Error('Unsupported paint');
      values.set(key, value);
    }
    if (rest.slice(offset).trim()) throw new Error('Malformed attributes');
    if (!stack.length) {
      if (name !== 'svg' || ++roots !== 1 || selfClosing || values.get('viewBox') !== '0 0 24 24') throw new Error('Expected one 24x24 SVG root');
      innerStart = position;
    } else if (name === 'svg') throw new Error('Nested SVG is unsupported');
    if (!selfClosing) stack.push(name);
  }
  if (source.slice(position).trim() || stack.length || roots !== 1 || innerEnd < innerStart) throw new Error('Incomplete SVG');
  return source.slice(innerStart, innerEnd).trim();
}

export async function buildIcons(check = false) {
  const files = (await readdir(catalog)).filter((name) => name.endsWith('.svg')).sort();
  const entries = [];
  for (const file of files) {
    const name = file.slice(0, -4);
    if (!/^[a-z][a-z0-9-]*$/.test(name)) throw new Error(`Invalid icon filename: ${file}`);
    try {
      entries.push([name, validateSvg(await readFile(new URL(file, catalog), 'utf8'))]);
    } catch (error) {
      throw new Error(`${file}: ${error.message}`);
    }
  }
  const names = entries.map(([name]) => JSON.stringify(name)).join(' | ');
  const output = `// Generated by scripts/build-icons.mjs. Do not edit.\nexport type IconName = ${names || 'never'};\n\nexport const ICONS: Record<IconName, string> = ${JSON.stringify(Object.fromEntries(entries), null, 2)};\n`;
  if (check) {
    const current = await readFile(target, 'utf8').catch((error) => { if (error.code === 'ENOENT') return ''; throw error; });
    if (current !== output) throw new Error('Icon output is stale. Run npm run icons.');
  } else await writeFile(target, output);
}

if (typeof process !== 'undefined' && process.argv[1] === fileURLToPath(import.meta.url)) {
  await buildIcons(process.argv.includes('--check'));
}
